-- Отдельная таблица пользователей: аккаунты сохраняются между перезапусками.
-- Старые учётные записи из InMemoryUserDetailsManager не переносим автоматически.
CREATE TABLE person_lab_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT person_lab_username_length_chk CHECK (length(username) BETWEEN 3 AND 40),
    CONSTRAINT person_lab_username_nonblank_chk CHECK (username ~ '[^[:space:]]'),
    CONSTRAINT person_lab_username_lower_chk CHECK (username = lower(username))
);

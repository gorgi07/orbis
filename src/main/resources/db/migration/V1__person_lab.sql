CREATE TABLE person_lab_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  x BIGINT NOT NULL,
  y REAL NOT NULL,
  name VARCHAR(200),
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT person_lab_location_name_chk CHECK (name IS NULL OR name ~ '[^[:space:]]'),
  CONSTRAINT person_lab_location_y_finite_chk CHECK (y > '-Infinity'::real AND y < 'Infinity'::real)
);
CREATE TABLE person_lab_people (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  name VARCHAR(200) NOT NULL,
  coord_x INTEGER NOT NULL,
  coord_y DOUBLE PRECISION NOT NULL,
  creation_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  eye_color VARCHAR(16),
  hair_color VARCHAR(16),
  location_id BIGINT REFERENCES person_lab_locations(id) ON DELETE RESTRICT,
  height DOUBLE PRECISION NOT NULL,
  weight DOUBLE PRECISION NOT NULL,
  nationality VARCHAR(32),
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT person_lab_name_chk CHECK (name ~ '[^[:space:]]'),
  CONSTRAINT person_lab_height_chk CHECK (height > 0 AND height < 'Infinity'::float8),
  CONSTRAINT person_lab_weight_chk CHECK (weight > 0 AND weight < 'Infinity'::float8),
  CONSTRAINT person_lab_coord_y_chk CHECK (coord_y > '-Infinity'::float8 AND coord_y < 'Infinity'::float8),
  CONSTRAINT person_lab_eyes_chk CHECK (eye_color IS NULL OR eye_color IN ('RED','BLUE','YELLOW')),
  CONSTRAINT person_lab_hair_chk CHECK (hair_color IS NULL OR hair_color IN ('RED','BLUE','YELLOW')),
  CONSTRAINT person_lab_nationality_chk CHECK (nationality IS NULL OR nationality IN ('USA','INDIA','ITALY','SOUTH_KOREA'))
);
CREATE INDEX person_lab_people_location_idx ON person_lab_people(location_id);
CREATE INDEX person_lab_people_creation_idx ON person_lab_people(creation_date DESC);
CREATE TABLE person_lab_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor VARCHAR(150) NOT NULL,
  entity_kind VARCHAR(40) NOT NULL,
  entity_id VARCHAR(50),
  action VARCHAR(40) NOT NULL,
  details TEXT NOT NULL,
  happened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE person_lab_idempotency (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor VARCHAR(150) NOT NULL,
  request_key VARCHAR(120) NOT NULL,
  operation VARCHAR(80) NOT NULL,
  fingerprint VARCHAR(1000) NOT NULL,
  result_id INTEGER,
  UNIQUE (actor, request_key)
);
